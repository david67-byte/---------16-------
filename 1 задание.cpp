#include <iostream>  // Подключаем библиотеку для ввода/вывода (cin, cout)
#include <string>    // Подключаем библиотеку для работы со строками
#include <stack>     // Подключаем библиотеку для работы со стеком
using namespace std; // Используем стандартное пространство имён

int main() { // Главная функция программы
    string s; // Переменная для хранения введённой строки
    getline(cin, s); // Считываем всю строку целиком, включая пробелы

    stack<char> st; // Создаём стек для хранения открывающих скобок
    bool ok = true; // Флаг: true = последовательность правильная, false = ошибка

    for (char c : s) { // Проходим по каждому символу строки
        if (c == '(' || c == '[' || c == '{') { // Если встретили открывающую скобку
            st.push(c); // Кладём её в стек
        } else if (c == ')' || c == ']' || c == '}') { // Если встретили закрывающую скобку
            if (st.empty()) { // Если стек пуст — для этой скобки нет пары
                ok = false; // Фиксируем ошибку
                break; // Прерываем цикл
            }
            char top = st.top(); // Запоминаем скобку на вершине стека
            st.pop(); // Удаляем её из стека (она нашла свою пару)

            // Проверяем, что закрывающая скобка совпадает с открывающей
            if ((c == ')' && top != '(') || 
                (c == ']' && top != '[') || 
                (c == '}' && top != '{')) {
                ok = false; // Если не совпадает — ошибка
                break; // Прерываем цикл
            }
        }
    }

    if (!st.empty()) ok = false; // Если остались незакрытые скобки — тоже ошибка

    cout << (ok ? "yes" : "no") << endl; // Выводим "yes", если всё хорошо, иначе "no"
    return 0; // Завершаем программу
}